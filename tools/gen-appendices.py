#!/usr/bin/env python3
"""T-04 (#6): generate Appendices A-D from the NoETL server's DSL artifacts.

The server commits three machine-readable files under
orchestrate-core/schema/ and fails its own build if they drift from the
Rust types that define the grammar (noetl/server
orchestrate-core/tests/dsl_artifacts.rs):

  playbook.schema.json   the playbook grammar (JSON Schema)       -> Appendix A
  dsl-manifest.json      tool kinds, gates, metadata extensions   -> Appendix B, C
  resource-model.json    labelled time / slot / limit figures     -> Appendix B, D

This script reads those files at the commit pinned in tools/SERVER_SCHEMA_PIN
and writes the four appendix pages. Output is deterministic: the same pin
produces byte-identical pages, so CI can regenerate and `git diff --exit-code`.

Usage:
  tools/gen-appendices.py --schema-dir <dir with the three files> [--out src]
  tools/gen-appendices.py --fetch          # download them at the pin first

Hand-written text lives only in this file (short intros) and in
tools/appendix-links.json (which chapter teaches each key).
Python 3.9+, standard library only.
"""
import argparse
import json
import os
import re
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
FILES = ("playbook.schema.json", "dsl-manifest.json", "resource-model.json")
STATUS_REAL = '<span class="status status-real">REAL</span>'


def read_pin():
    pin = {}
    with open(os.path.join(HERE, "SERVER_SCHEMA_PIN")) as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                pin[k.strip()] = v.strip()
    for k in ("repo", "commit", "tag", "date"):
        if k not in pin:
            sys.exit(f"SERVER_SCHEMA_PIN: missing {k}")
    return pin


def fetch(pin, dest):
    os.makedirs(dest, exist_ok=True)
    for name in FILES:
        url = (f"https://raw.githubusercontent.com/{pin['repo']}/{pin['commit']}"
               f"/orchestrate-core/schema/{name}")
        with urllib.request.urlopen(url, timeout=60) as r:
            data = r.read()
        with open(os.path.join(dest, name), "wb") as f:
            f.write(data)


# ---------------------------------------------------------------- helpers

def esc(s):
    """Make a value safe inside a Markdown table cell."""
    if s is None:
        return ""
    s = str(s).replace("\r", "")
    s = s.replace("|", "\\|").replace("\n", " ")
    # rustdoc intra-doc links ([`Type`]) have no target outside rustdoc.
    s = re.sub(r"\[(`[^`\]]+`)\](?![(\[])", r"\1", s)
    # Source text is prose, not Markdown links: escape brackets so
    # `[{id, name}]` is not read as a reference link.
    s = s.replace("[", "\\[").replace("]", "\\]")
    # mdBook preprocessors scan for {{# ... }}; never emit that sequence.
    s = s.replace("{{", "{ {").replace("}}", "} }")
    return s.strip()


def code(s):
    return f"`{s}`" if s not in (None, "") else ""


def jtype(p):
    """Human-readable type of a JSON-schema property."""
    if not isinstance(p, dict):
        return ""
    if "$ref" in p:
        return p["$ref"].split("/")[-1]
    if "anyOf" in p:
        parts = [jtype(x) for x in p["anyOf"]]
        return " \\| ".join(x for x in parts if x) or "any"
    if "oneOf" in p:
        parts = [jtype(x) for x in p["oneOf"]]
        return " \\| ".join(x for x in parts if x) or "any"
    if "const" in p:
        return f'"{p["const"]}"'
    if "enum" in p:
        return " \\| ".join(f'"{e}"' for e in p["enum"])
    t = p.get("type")
    if isinstance(t, list):
        t = [x for x in t]
    else:
        t = [t] if t else []
    out = []
    for x in t:
        if x == "array":
            out.append(f"array of {jtype(p.get('items', {})) or 'any'}")
        elif x == "object" and "additionalProperties" in p and isinstance(p["additionalProperties"], dict):
            out.append(f"map of {jtype(p['additionalProperties'])}")
        else:
            out.append(x)
    return " \\| ".join(out) if out else "any"


def first_para(text):
    if not text:
        return ""
    return text.strip().split("\n\n")[0].replace("\n", " ")


def anchor(name):
    return name.lower().replace("_", "-").replace(".", "-")


def header(title, pin, sources, intro):
    lines = [
        f"# {title}",
        "",
        STATUS_REAL,
        "",
        "<!-- GENERATED by tools/gen-appendices.py. Do not edit by hand:",
        "     change the generator or the pin (tools/SERVER_SCHEMA_PIN) and regenerate. -->",
        "",
        "```admonish note title=\"Generated\"",
        f"Generated from `{pin['repo']}` **{pin['tag']}** "
        f"(commit `{pin['commit'][:12]}`, {pin['date']}), "
        f"file{'s' if len(sources) > 1 else ''} "
        + ", ".join(f"`orchestrate-core/schema/{s}`" for s in sources)
        + ". The server's own tests fail if these files drift from the code "
        "that defines the grammar, so this page is as current as the pin.",
        "```",
        "",
    ]
    lines += intro
    lines.append("")
    return lines


def link_for(links, key):
    tgt = links.get(key)
    if not tgt:
        return ""
    page, label = tgt
    return f"[{label}]({page})"


# ---------------------------------------------------------------- Appendix A

def appendix_a(schema, pin, links):
    defs = schema.get("$defs", {})
    L = header(
        "Appendix A: DSL Reference",
        pin, ["playbook.schema.json"],
        [
            f"Every key of a NoETL playbook (`{schema.get('$id', '')}`), "
            "as the grammar defines it. Chapters 4–6 teach these keys; the "
            "*Taught in* column links to the chapter.",
            "",
            f"> {esc(first_para(schema.get('description')))}",
        ],
    )
    req = set(schema.get("required", []))
    L += ["## Top-level keys", "",
          "| Key | Type | Required | Description | Taught in |",
          "|---|---|---|---|---|"]
    for k in sorted(schema.get("properties", {})):
        p = schema["properties"][k]
        L.append(f"| `{k}` | {jtype(p)} | {'yes' if k in req else ''} | "
                 f"{esc(first_para(p.get('description')))} | {link_for(links, k)} |")
    L.append("")
    L += ["## Types", "",
          "Each type below is a `$defs` entry of the schema. Types are listed "
          "alphabetically.", ""]
    for name in sorted(defs):
        d = defs[name]
        L += [f"### {name}", ""]
        desc = first_para(d.get("description"))
        if desc:
            L += [esc(desc), ""]
        tl = link_for(links, name)
        if tl:
            L += [f"Taught in {tl}.", ""]
        props = d.get("properties")
        if props:
            dreq = set(d.get("required", []))
            L += ["| Key | Type | Required | Default | Description |",
                  "|---|---|---|---|---|"]
            for k in sorted(props):
                p = props[k]
                dflt = p.get("default", None)
                dflt_s = "" if dflt is None else code(json.dumps(dflt))
                L.append(f"| `{k}` | {jtype(p)} | {'yes' if k in dreq else ''} | "
                         f"{dflt_s} | {esc(first_para(p.get('description')))} |")
            L.append("")
        for alt in ("oneOf", "anyOf"):
            if alt in d and not props:
                L += ["One of:", ""]
                for x in d[alt]:
                    L.append(f"- {jtype(x)}" + (f": {esc(first_para(x.get('description')))}"
                                                 if x.get("description") else ""))
                L.append("")
        if "enum" in d:
            L += ["Values: " + ", ".join(f"`{e}`" for e in d["enum"]), ""]
    return L


# ---------------------------------------------------------------- Appendix B

def appendix_b(manifest, model, pin, links, local):
    kinds = {k["name"]: k for k in manifest.get("tool_kinds", [])}
    prof = {k["kind"]: k for k in model.get("step_kinds", {}).get("kinds", [])}
    local_set = set(local.get("kinds", []))
    L = header(
        "Appendix B: Tool Kinds Reference",
        pin, ["dsl-manifest.json", "resource-model.json"],
        [
            "Every `tool.kind` the server's parser accepts, whether it is on "
            "by default, how it executes on a worker, how long it holds a "
            "worker slot, and its default timeout. Chapter 5 teaches tools.",
            "",
            "*Parser accepts by default* means the server accepts the kind in a "
            "playbook with no flag set; whether a given worker can execute it is a "
            "separate question (see the note below). An empty profile cell means the "
            "resource model has not profiled that kind.",
            "",
            "The **Accepted locally** column is not from the server: it is the local "
            f"runtime's kind list at NoETL CLI **v{local.get('cli_version', '?')}** "
            f"({esc(local.get('source', ''))}). Chapter 8 covers the local runtime.",
            "",
            f"> {esc(manifest.get('executable_note', ''))}",
        ],
    )
    L += ["## Summary", "",
          "| Kind | Parser accepts by default | Gate | Accepted locally | Execution (worker) | Holds a slot | Default timeout |",
          "|---|---|---|---|---|---|---|"]
    for name in sorted(set(kinds) | set(prof)):
        k = kinds.get(name, {})
        p = prof.get(name, {})
        en = k.get("enabled")
        en_s = "yes" if en else ("**no**" if en is False else "?")
        gate = code(k.get("gate_env")) if k.get("gated") else ""
        to = p.get("timeout") or {}
        if to:
            v = to.get("value")
            tos = "none" if v is None else f"{v} {to.get('unit', '')}".strip()
            tos += f" ({to.get('label')})" if to.get("label") else ""
            if to.get("env"):
                tos += f", {code(to['env'])}"
        else:
            tos = ""
        loc = "yes" if name in local_set else ""
        L.append(f"| [`{name}`](#{anchor('kind-' + name)}) | {en_s} | {gate} | {loc} | "
                 f"{esc(p.get('execution'))} | {esc(p.get('holds_slot'))} | {esc(tos)} |")
    extra_local = sorted(local_set - set(kinds) - set(prof))
    L.append("")
    if extra_local:
        L += ["Kinds the local runtime accepts that the server's parser does not: "
              + ", ".join(f"`{k}`" for k in extra_local) + ".", ""]
    sk = model.get("step_kinds", {})
    if sk.get("kinds_note"):
        L += [f"> {esc(sk['kinds_note'])}", ""]
    for key in ("slot_rule", "no_global_timeout", "retry_config_inert"):
        r = sk.get(key)
        if isinstance(r, dict):
            L += [f"- **{key.replace('_', ' ')}** ({r.get('label', '')}): "
                  f"{esc(r.get('text'))} *Source: {esc(r.get('source'))}*"]
    L += ["", "## Kinds", ""]
    for name in sorted(set(kinds) | set(prof)):
        k = kinds.get(name, {})
        p = prof.get(name, {})
        L += [f"### kind-{name}", "", f"`kind: {name}`", ""]
        if k.get("gated"):
            L += [f"- Gated: off unless the server sets {code(k.get('gate_env'))}"
                  + (f" and the worker sets {code(k.get('worker_gate_env'))}" if k.get("worker_gate_env") else "")
                  + "."]
        if k.get("availability"):
            L += [f"- Availability: {esc(k['availability'])}"]
        for f in ("execution", "holds_slot", "memory_class", "durability", "deadlock_note"):
            if p.get(f):
                L += [f"- {f.replace('_', ' ').capitalize()}: {esc(p[f])}"]
        if p.get("aliases"):
            L += [f"- Aliases: {', '.join(code(a) for a in p['aliases'])}"]
        to = p.get("timeout")
        if to:
            v = to.get("value")
            L += [f"- Timeout ({to.get('label', '')}): "
                  + ("none" if v is None else f"{v} {to.get('unit', '')}".strip())
                  + (f", env {code(to['env'])}" if to.get("env") else "")
                  + (f". {esc(to.get('meaning'))}" if to.get("meaning") else "")
                  + f" *Source: {esc(to.get('source'))}*"]
        for ol in p.get("other_limits", []) or []:
            L += [f"- Limit: {esc(flat(ol))}"]
        for m in p.get("measured", []) or []:
            L += [f"- {m.get('label', '')}: {esc(m.get('what'))}: **{esc(m.get('value'))}** "
                  f"({esc(m.get('environment'))}, {esc(m.get('date'))}; source: {esc(m.get('source'))})"]
        if name in local_set:
            L += ["- Local runtime: accepted by the parser (Chapter 8 covers what it does there)."]
        L.append("")
    return L


def flat(v):
    """One-line rendering of a nested value, keys in sorted order."""
    if isinstance(v, dict):
        return "; ".join(f"{k}: {flat(v[k])}" for k in sorted(v))
    if isinstance(v, list):
        return ", ".join(flat(x) for x in v)
    if v is None:
        return "none"
    return str(v)


# ---------------------------------------------------------------- Appendix C

def appendix_c(manifest, model, pin):
    L = header(
        "Appendix C: Feature Flags and Environment Variables",
        pin, ["dsl-manifest.json", "resource-model.json"],
        [
            "The flags and environment variables the DSL artifacts name: the "
            "gates on tool kinds and DSL features, and the limits a worker "
            "reads. It is **not** every environment variable the server and "
            "worker read; only those the artifacts publish.",
        ],
    )
    rows = []
    for k in manifest.get("tool_kinds", []):
        if k.get("gate_env"):
            rows.append((k["gate_env"], "server", f"enables `kind: {k['name']}`",
                         "off" if not k.get("enabled") else "on", ""))
        if k.get("worker_gate_env"):
            rows.append((k["worker_gate_env"], "worker", f"lets a worker run `kind: {k['name']}`", "off", ""))
    for m in manifest.get("metadata_extensions", []):
        if m.get("server_gate_env"):
            rows.append((m["server_gate_env"], "server", f"serves `{m.get('path')}`: {m.get('serves', '')}", "off",
                         ", ".join(m.get("requires_env", []) or [])))
        if m.get("callback_origins_env"):
            rows.append((m["callback_origins_env"], "server", f"allowed callback origins for `{m.get('path')}`", "", ""))
    cf = manifest.get("catalog_features", {})
    for f in cf.get("features", []):
        if f.get("server_gate_env"):
            req = f.get("requires_env", []) or f.get("delegate_requires_env", []) or []
            rows.append((f["server_gate_env"], "server", f"catalog: {f.get('name')}: {f.get('serves') or f.get('affects') or ''}",
                         "off", ", ".join(req)))
    seen = {}
    for r in rows:
        seen.setdefault(r[0], r)
    L += ["## Gates", "",
          (f"> {esc(cf.get('default'))}" if cf.get("default") else ""), "",
          "| Variable | Read by | What it enables | Default | Requires |",
          "|---|---|---|---|---|"]
    for name in sorted(seen):
        v, by, what, d, req = seen[name]
        L.append(f"| `{v}` | {by} | {esc(what)} | {d} | {', '.join(code(x) for x in req.split(', ')) if req else ''} |")
    L.append("")
    L += ["## Limits", "",
          "| Variable | Default | Unit | Note | Source |", "|---|---|---|---|---|"]
    lim = [x for x in model.get("limits", []) if x.get("env")]
    for x in sorted(lim, key=lambda x: x["env"]):
        L.append(f"| `{x['env']}` | {esc(flat(x.get('value')))} ({x.get('label', '')}) | {esc(x.get('unit'))} | "
                 f"{esc(x.get('note'))} | {esc(x.get('source'))} |")
    L.append("")
    wr = manifest.get("worker_runtime", {})
    budgets = (wr.get("agent") or {}).get("budgets", [])
    if budgets:
        L += ["## Agent budgets", "", "| Variable | Default | Scope |", "|---|---|---|"]
        for b in sorted(budgets, key=lambda b: b.get("env", "")):
            L.append(f"| `{b.get('env')}` | {esc(b.get('default'))} | {esc(b.get('scope'))} |")
        L.append("")
    return L


# ---------------------------------------------------------------- Appendix D

MEASURE_COLS = ("label", "what", "value", "environment", "date", "source", "note")


def is_measure_list(v):
    return isinstance(v, list) and v and all(isinstance(x, dict) and "label" in x for x in v)


def measure_table(items):
    cols = [c for c in MEASURE_COLS if any(c in x for x in items)]
    extra = sorted({k for x in items for k in x} - set(cols))
    cols += extra
    out = ["| " + " | ".join(c.capitalize() for c in cols) + " |",
           "|" + "---|" * len(cols)]
    for x in items:
        out.append("| " + " | ".join(esc(flat(x.get(c))) if c in x else "" for c in cols) + " |")
    return out


def render_any(key, v, depth):
    h = "#" * min(depth, 6)
    out = []
    if isinstance(v, dict):
        out += [f"{h} {key}", ""]
        scalars = {k: x for k, x in v.items() if not isinstance(x, (dict, list))}
        for k in sorted(scalars):
            out.append(f"- **{k}**: {esc(flat(scalars[k]))}")
        if scalars:
            out.append("")
        for k in sorted(v):
            x = v[k]
            if isinstance(x, (dict, list)):
                out += render_any(k, x, depth + 1)
    elif is_measure_list(v):
        out += [f"{h} {key}", ""] + measure_table(v) + [""]
    elif isinstance(v, list):
        out += [f"{h} {key}", ""]
        for x in v:
            out.append(f"- {esc(flat(x))}")
        out.append("")
    else:
        out += [f"- **{key}**: {esc(flat(v))}", ""]
    return out


def appendix_d(model, pin):
    L = header(
        "Appendix D: The Resource Model, Annotated",
        pin, ["resource-model.json"],
        [
            "The NoETL resource model: what a playbook costs in time, worker "
            "slots, memory, fuel and tool calls, with every figure labelled. "
            "The same file is published at `noetl.ai/dsl/resource-model.json`. "
            "Chapter 21 explains how to use it.",
            "",
            f"Model version **{model.get('model_version')}**, figures as of "
            f"**{model.get('as_of')}**. Purpose: {esc(model.get('purpose'))}",
            "",
            "```admonish warning title=\"Read this first\"",
        ] + [f"- {x}" for x in model.get("read_first", [])] + ["```"],
    )
    labels = model.get("labels", {})
    if labels:
        L += ["## Labels", "", "| Label | Meaning |", "|---|---|"]
        for k in sorted(labels):
            L.append(f"| **{k}** | {esc(labels[k])} |")
        L.append("")
    if model.get("limits"):
        L += ["## Limits", ""] + measure_table(model["limits"]) + [""]
    skip = {"as_of", "labels", "limits", "model_version", "purpose", "read_first", "step_kinds"}
    for k in sorted(model):
        if k in skip:
            continue
        L += render_any(k.replace("_", " ").capitalize(), model[k], 2)
    L += ["## Step kinds", "",
          "Per-kind execution, slot and timeout profiles are in "
          "[Appendix B](appendix-02-tool-kinds.md).", ""]
    return L


# ---------------------------------------------------------------- main

def write(path, lines):
    text = "\n".join(lines).rstrip("\n") + "\n"
    while "\n\n\n" in text:
        text = text.replace("\n\n\n", "\n\n")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--schema-dir", default=os.path.join(ROOT, ".schema-cache"))
    ap.add_argument("--out", default=os.path.join(ROOT, "src"))
    ap.add_argument("--fetch", action="store_true", help="download the files at the pin first")
    a = ap.parse_args()
    pin = read_pin()
    if a.fetch:
        fetch(pin, a.schema_dir)
    load = lambda n: json.load(open(os.path.join(a.schema_dir, n), encoding="utf-8"))
    schema, manifest, model = (load(n) for n in FILES)
    links = json.load(open(os.path.join(HERE, "appendix-links.json")))
    local = json.load(open(os.path.join(HERE, "local-kinds.json")))
    write(os.path.join(a.out, "appendix-01-dsl-reference.md"), appendix_a(schema, pin, links))
    write(os.path.join(a.out, "appendix-02-tool-kinds.md"), appendix_b(manifest, model, pin, links, local))
    write(os.path.join(a.out, "appendix-03-flags.md"), appendix_c(manifest, model, pin))
    write(os.path.join(a.out, "appendix-04-resource-model.md"), appendix_d(model, pin))


if __name__ == "__main__":
    main()
